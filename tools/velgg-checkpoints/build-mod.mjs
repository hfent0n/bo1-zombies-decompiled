// Bundles the extension's mods into src/mod-files.js (globalThis.VELGG_CP_MOD_FILES = { "mods/<name>/...": text }),
// which content.js hands to page.js to write into each map pack's OPFS folder. Run after editing any of them:
//   node tools/velgg-checkpoints/build-mod.mjs
// Sources: this folder's mod/<name>/ (checkpoint, tweaks) and the repo's own mods/sandbox (its maps/sandbox/ scripts
// only: its maps/zombie_pentagon_ffotd.gsc is the fs_game entry point, which under fs_mods mods/_stack provides).
import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { join, relative, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const SOURCES = [
  { name: 'checkpoint', dir: join(here, 'mod', 'checkpoint') },
  { name: 'tweaks', dir: join(here, 'mod', 'tweaks') },
  // scripts only: its mod.ff is binary, fetched from the extension at run time (content.js), never bundled here
  { name: 'halo', dir: join(here, 'mod', 'halo') },
  { name: 'sandbox', dir: join(here, '..', '..', 'mods', 'sandbox'), only: /^maps\/sandbox\// },
];
const files = {};
for (const { name, dir, only } of SOURCES) {
  (function walk(at) {
    for (const entry of readdirSync(at).sort()) {
      const path = join(at, entry);
      if (statSync(path).isDirectory()) { walk(path); continue; }
      const rel = relative(dir, path).split('\\').join('/');
      if (!/\.(gsc|csc|cfg)$/i.test(rel) || (only && !only.test(rel))) continue;
      files[`mods/${name}/${rel}`.toLowerCase()] = readFileSync(path, 'utf8').replace(/\r\n/g, '\n');
    }
  })(dir);
}
writeFileSync(join(here, 'src', 'mod-files.js'),
  '// Generated by build-mod.mjs - do not edit.\nglobalThis.VELGG_CP_MOD_FILES = ' + JSON.stringify(files, null, 1) + ';\n');
console.log(Object.keys(files).map(p => `${p} (${files[p].length} chars)`).join('\n'));
